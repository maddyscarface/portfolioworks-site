/** Every public route: hand-written utility/conversion rows plus generated service, guide and market rows. */
export function allRouteBriefs(): RouteBrief[] {
  const byPath = new Map(contentInventory.map((row) => [row.path, row]));
  const add = (row: RouteBrief) => {
    if (!byPath.has(row.path)) byPath.set(row.path, row);
  };

  for (const s of services.filter((item) => item.href.startsWith("/services/"))) {
    add({
      path: s.href,
      audience: "Landlords, investors and property managers",
      queryGroup: s.name.toLowerCase(),
      stage: "commercial",
      primaryKeyword: s.seoTitle.replace(" | PortfolioWorks", "").toLowerCase(),
      secondary: [],
      h1: s.name,
      title: s.seoTitle,
      description: s.seoDescription,
      indexable: true,
      evidence: "Service catalog entry; pricing only when a written scope is approved.",
      cta: { label: s.cta ?? "Request a written scope", href: "/request-a-property-walkthrough" },
      schema: ["Service", "WebPage", "BreadcrumbList"],
      region: "Greater Boston, MA",
    });
  }

  for (const g of allGuides()) {
    add({
      path: `/resources/${g.slug}`,
      audience: g.audience,
      queryGroup: g.primaryKw,
      stage: g.intent === "commercial" ? "commercial" : "informational",
      primaryKeyword: g.primaryKw,
      secondary: g.secondary,
      h1: g.h1,
      title: g.seoTitle,
      description: g.description,
      indexable: g.indexable !== false,
      evidence: g.market === "FL" || g.market === "ME" ? "Forthcoming-market article; noindex and not in the sitemap." : "Original operational guide; no vacancy or capacity guarantees.",
      cta: { label: "Request a written scope", href: "/request-a-turnover" },
      schema: ["Article", "WebPage", "BreadcrumbList"],
      region: g.market === "MA" || g.market === "all" ? "Greater Boston, MA" : g.market === "FL" ? "Southeast Florida (not active)" : "Southern Maine (not active)",
    });
  }

  for (const m of markets) {
    add({
      path: `/markets/${m.id}`,
      audience: "Owners checking market coverage",
      queryGroup: `${m.short} rental contractor`,
      stage: "commercial",
      primaryKeyword: `${m.short} rental turnovers`,
      secondary: [],
      h1: m.headline,
      title: marketPageTitle(m),
      description: marketPageDescription(m),
      indexable: isIndexable(m),
      evidence: isIndexable(m) ? "Launch market only." : "Forthcoming market; noindex and excluded from the sitemap.",
      cta: { label: "Request a Property Walkthrough", href: "/request-a-property-walkthrough" },
      schema: ["WebPage", "BreadcrumbList"],
      region: `${m.short}, ${m.state}`,
    });
  }

  for (const { market, town } of servedTowns()) {
    add({
      path: `/markets/${market.id}/${town.slug}`,
      audience: "Landlords and property managers in this town",
      queryGroup: `${town.name} rental turnovers`,
      stage: "commercial",
      primaryKeyword: `${town.name} rental turnovers`,
      secondary: [],
      h1: `Rental turnovers and renovations in ${town.name}, ${market.state}`,
      title: townPageTitle(town),
      description: townPageDescription(town, market),
      indexable: isIndexable(market),
      evidence: isIndexable(market) ? "Served launch-market town." : "Town page exists but is noindex until the market launches.",
      cta: { label: "Request a Property Walkthrough", href: "/request-a-property-walkthrough" },
      schema: ["WebPage", "BreadcrumbList"],
      region: `${town.name}, ${market.state}`,
    });
  }

  return [...byPath.values()];
}
